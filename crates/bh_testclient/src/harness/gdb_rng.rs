//! RNG / call trace: gdb recipe for the reference, trace runner for ours, and the sequence diff.
//!

use std::path::Path;
use std::process::{Command, Stdio};
use std::time::{Duration, Instant};

use super::refenv::{OurServer, RefDebugServer, RunSpec, ServerHandle};
use super::{ref_binary, HarnessError, Result, TempDir};

/// One RNG event.
#[derive(Clone, Debug, PartialEq)]
pub struct RngEvent {
    /// 'R' rand, 'M' fn_rand, 'S' srand
    pub kind: char,
    pub seq: u64,
    pub tag: String,
    pub value: String,
}

/// Parse `<K> <seq> <tag> <value>` lines; blank and `#` lines ignored.
pub fn parse_trace(text: &str) -> Result<Vec<RngEvent>> {
    let mut out = Vec::new();
    for (n, line) in text.lines().enumerate() {
        let l = line.trim();
        if l.is_empty() || l.starts_with('#') {
            continue;
        }
        let mut it = l.split_whitespace();
        let bad = || HarnessError::Parse(format!("rng trace line {}: '{}'", n + 1, l));
        let k = it.next().ok_or_else(bad)?;
        let kind = match k {
            "R" | "M" | "S" => k.chars().next().unwrap(),
            _ => return Err(bad()),
        };
        let seq: u64 = it.next().ok_or_else(bad)?.parse().map_err(|_| bad())?;
        let tag = it.next().ok_or_else(bad)?.to_string();
        let value = it.next().ok_or_else(bad)?.to_string();
        out.push(RngEvent { kind, seq, tag, value });
    }
    Ok(out)
}

/// The verified gdb Python script (Appendix A). Env: `BH_RNG_OUT`, `BH_RNG_LIMIT`.
pub fn gdb_script_py() -> &'static str {
    r##"# generated by bh_testclient::harness::gdb_rng -- gdb python script (gdb >= 12, python3)
# env: BH_RNG_OUT (output file), BH_RNG_LIMIT (stop after N events, default 20000)
import gdb, os
OUT = open(os.environ.get("BH_RNG_OUT", "ref_rng_trace.log"), "w")
LIMIT = int(os.environ.get("BH_RNG_LIMIT", "20000"))
seq = [0]

def tag(frame):
    older = frame.older()
    if older is None:
        return "0x0@?"
    name = older.name() or "?"
    return "0x%x@%s" % (older.pc(), name.replace(" ", "_"))

def emit(kind, t, val):
    OUT.write("%s %d %s %s\n" % (kind, seq[0], t, val))
    seq[0] += 1
    if seq[0] >= LIMIT:
        OUT.flush()
        gdb.execute("kill")
        gdb.execute("quit")

class Fin(gdb.FinishBreakpoint):
    def __init__(self, kind, t):
        super().__init__(gdb.newest_frame(), internal=True)
        self.kind = kind
        self.t = t
    def stop(self):
        if self.kind == "R":
            emit("R", self.t, int(gdb.parse_and_eval("$eax")))
        else:
            emit("M", self.t, "%.17g" % float(gdb.parse_and_eval("$xmm0.v2_double[0]")))
        return False
    def out_of_scope(self):
        pass

class B(gdb.Breakpoint):
    def __init__(self, spec, kind):
        super().__init__(spec, internal=True)
        self.kind = kind
    def stop(self):
        t = tag(gdb.newest_frame())
        if self.kind == "S":
            emit("S", t, int(gdb.parse_and_eval("$edi")) & 0xffffffff)
        else:
            Fin(self.kind, t)
        return False

def on_exit(ev):
    OUT.flush()
gdb.events.exited.connect(on_exit)
gdb.execute("set breakpoint pending on")
B("rand", "R")
B("srand", "S")
B("*fn_rand", "M")
gdb.execute("continue")
OUT.flush()
"##
}

/// Run the reference under gdbserver + gdb for `limit` events.
pub fn run_reference_trace(args: &[String], limit: u64, out: &Path) -> Result<Vec<RngEvent>> {
    let srv = RefDebugServer::start(&RunSpec { tag: "rng".into(), args: args.to_vec(), ..Default::default() })?;
    let tmp = TempDir::new("gdbrng")?;
    let script = tmp.path().join("rng.py");
    std::fs::write(&script, gdb_script_py())?;
    let mut gdb = Command::new("gdb")
        .args([
            "-batch",
            "-nx",
            "-ex",
            "set pagination off",
            "-ex",
            "set debuginfod enabled off",
            "-ex",
            "set sysroot target:",
            "-ex",
        ])
        .arg(format!("target remote 127.0.0.1:{}", srv.gdb_port()))
        .arg("-x")
        .arg(&script)
        .arg(ref_binary())
        .env("BH_RNG_OUT", out)
        .env("BH_RNG_LIMIT", limit.to_string())
        .stdin(Stdio::null())
        .stdout(Stdio::null())
        .stderr(Stdio::null())
        .spawn()
        .map_err(|e| HarnessError::Io(e))?;
    let end = Instant::now() + Duration::from_secs(600);
    loop {
        match gdb.try_wait()? {
            Some(_) => break,
            None => {
                if Instant::now() >= end {
                    let _ = gdb.kill();
                    let _ = gdb.wait();
                    return Err(HarnessError::Timeout("gdb did not finish within 600 s".into()));
                }
                std::thread::sleep(Duration::from_millis(100));
            }
        }
    }
    drop(srv); // docker rm -f
    let text = std::fs::read_to_string(out)?;
    parse_trace(&text)
}

/// Run OUR server with `BH_RNG_TRACE=<out>` (+ `BH_VIRTUAL_CLOCK`) until `limit` lines exist or it exits.
pub fn run_our_trace(
    args: &[String],
    virtual_clock_unix: Option<u64>,
    limit: u64,
    out: &Path,
) -> Result<Vec<RngEvent>> {
    let _ = std::fs::remove_file(out);
    let mut env = vec![("BH_RNG_TRACE".to_string(), out.display().to_string())];
    if let Some(c) = virtual_clock_unix {
        env.push(("BH_VIRTUAL_CLOCK".into(), c.to_string()));
    }
    let mut srv =
        OurServer::start(&RunSpec { tag: "rngours".into(), args: args.to_vec(), data_dir: None, env, console: false })?;
    let end = Instant::now() + Duration::from_secs(600);
    loop {
        let lines = std::fs::read(out).map(|b| b.iter().filter(|c| **c == b'\n').count() as u64).unwrap_or(0);
        if lines >= limit {
            break;
        }
        if !srv.is_running() {
            break;
        }
        if Instant::now() >= end {
            let _ = srv.stop_sigint(Duration::from_secs(5));
            return Err(HarnessError::Timeout(format!("our trace reached only {} of {} events", lines, limit)));
        }
        std::thread::sleep(Duration::from_millis(50));
    }
    let _ = srv.stop_sigint(Duration::from_secs(5));
    let text = std::fs::read_to_string(out).unwrap_or_default();
    // a SIGKILLed writer may leave a partial last line: only complete lines are parsed
    let complete = match text.rfind('\n') {
        Some(p) => &text[..=p],
        None => "",
    };
    let mut ev = parse_trace(complete)?;
    ev.truncate(limit as usize);
    Ok(ev)
}

/// Seed of the FIRST 'S' event (= `time(NULL)` of the reference run): the `BH_VIRTUAL_CLOCK` for ours.
pub fn first_srand_seed(trace: &[RngEvent]) -> Option<u32> {
    trace.iter().find(|e| e.kind == 'S').and_then(|e| e.value.parse::<u32>().ok())
}

/// First divergence of two traces.
#[derive(Clone, Debug)]
pub struct RngDivergence {
    pub index: usize,
    pub reference: RngEvent,
    pub ours: Option<RngEvent>,
    /// previous (up to 8) pairs
    pub context: Vec<(Option<RngEvent>, Option<RngEvent>)>,
}
/// Result of `diff_rng`.
#[derive(Clone, Debug)]
pub struct RngDiff {
    pub compared: usize,
    pub ref_len: usize,
    pub ours_len: usize,
    pub first: Option<RngDivergence>,
}

fn values_equal(a: &RngEvent, b: &RngEvent) -> bool {
    if a.kind != b.kind {
        return false;
    }
    match a.kind {
        'M' => match (a.value.parse::<f64>(), b.value.parse::<f64>()) {
            (Ok(x), Ok(y)) => x.to_bits() == y.to_bits() || (x.is_nan() && y.is_nan()),
            _ => a.value == b.value,
        },
        _ => match (a.value.parse::<i64>(), b.value.parse::<i64>()) {
            (Ok(x), Ok(y)) => x == y,
            _ => a.value == b.value,
        },
    }
}

/// Compare `(kind, value)` sequences (tags are informational).
pub fn diff_rng(reference: &[RngEvent], ours: &[RngEvent], require_equal_len: bool) -> RngDiff {
    let n = reference.len().min(ours.len());
    let ctx = |i: usize| -> Vec<(Option<RngEvent>, Option<RngEvent>)> {
        (i.saturating_sub(8)..i).map(|j| (reference.get(j).cloned(), ours.get(j).cloned())).collect()
    };
    let mut first = None;
    for i in 0..n {
        if !values_equal(&reference[i], &ours[i]) {
            first = Some(RngDivergence {
                index: i,
                reference: reference[i].clone(),
                ours: Some(ours[i].clone()),
                context: ctx(i),
            });
            break;
        }
    }
    if first.is_none() && require_equal_len && reference.len() != ours.len() {
        let reference_ev = reference.get(n).cloned().unwrap_or(RngEvent {
            kind: '-',
            seq: n as u64,
            tag: "<end of reference>".into(),
            value: String::new(),
        });
        first = Some(RngDivergence { index: n, reference: reference_ev, ours: ours.get(n).cloned(), context: ctx(n) });
    }
    RngDiff { compared: n, ref_len: reference.len(), ours_len: ours.len(), first }
}

impl RngDiff {
    /// No divergence and at least one event compared.
    pub fn is_clean(&self) -> bool {
        self.first.is_none() && self.compared > 0
    }
    pub fn render(&self) -> String {
        let mut s = format!("rng events: ref={} ours={} compared={}\n", self.ref_len, self.ours_len, self.compared);
        if self.compared == 0 {
            s.push_str("WARNING: nothing was compared\n");
        }
        match &self.first {
            None => {
                if self.ref_len != self.ours_len {
                    s.push_str(&format!(
                        "tail: one side is longer ({} vs {} events); common prefix identical\n",
                        self.ref_len, self.ours_len
                    ));
                }
                s.push_str(if self.is_clean() { "RESULT: identical\n" } else { "RESULT: NOT CLEAN\n" });
            }
            Some(d) => {
                s.push_str(&format!("FIRST DIVERGENCE at index {}\n", d.index));
                let fmt = |e: &Option<RngEvent>| {
                    e.as_ref().map_or("<none>".to_string(), |e| format!("{} {} {} {}", e.kind, e.seq, e.tag, e.value))
                };
                for (a, b) in &d.context {
                    s.push_str(&format!("   ref : {}\n   ours: {}\n", fmt(a), fmt(b)));
                }
                s.push_str(&format!(">> ref : {}\n>> ours: {}\n", fmt(&Some(d.reference.clone())), fmt(&d.ours)));
                s.push_str("RESULT: DIFFERENT\n");
            }
        }
        s
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    const SAMPLE: &str = "S 0 CommandLineDelegate_init 1792192757\nR 1 BHServer_init 1234\nS 502 World_incrementalLoad 12345\nM 503 NoiseFunction_init 0.92899722604290513\nM 504 x 0.44308010778461587\nM 505 y 0.44916575785008395\n";

    /// S12.
    #[test]
    fn s12_parse_and_diff() {
        let a = parse_trace(SAMPLE).unwrap();
        assert_eq!(a.len(), 6);
        assert_eq!(first_srand_seed(&a), Some(1792192757));
        let b = parse_trace(&SAMPLE.replace("0.92899722604290513", "0.928997226042905130")).unwrap();
        assert!(diff_rng(&a, &b, true).is_clean());
        // 1 ulp change on the M at index 4
        let v: f64 = "0.44308010778461587".parse().unwrap();
        let bumped = f64::from_bits(v.to_bits() + 1);
        let c = parse_trace(&SAMPLE.replace("0.44308010778461587", &format!("{:.17e}", bumped))).unwrap();
        let d = diff_rng(&a, &c, false);
        assert_eq!(d.first.as_ref().unwrap().index, 4);
        assert!(!d.is_clean() && d.render().contains("FIRST DIVERGENCE at index 4"));
        // tags never matter; tail is not an error unless required
        let e = parse_trace(&SAMPLE.replace("BHServer_init", "other")).unwrap();
        assert!(diff_rng(&a, &e[..5], false).is_clean());
        assert!(!diff_rng(&a, &e[..5], true).is_clean());
        assert!(!diff_rng(&[], &[], false).is_clean());
        assert!(parse_trace("X 1 a b").is_err());
    }

    /// S13.
    #[test]
    fn s13_script_guards() {
        let s = gdb_script_py();
        for k in ["FinishBreakpoint", "$eax", "$xmm0.v2_double[0]", "*fn_rand"] {
            assert!(s.contains(k), "{}", k);
        }
    }
}
