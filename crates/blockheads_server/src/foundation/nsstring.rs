//! `NSString` semantics (GNUstep-base 1.24): UTF-16 lengths/ranges, hash, case mapping, comparison, number parsing,
//!
//! Note: a Rust `String` cannot hold unpaired surrogates; substrings that would split a surrogate pair are
//! converted lossily (the game never produces them from valid UTF-8 input).

use crate::foundation::exception::{ns_raise, range_exception_beyond_size};
use std::collections::HashMap;
use std::sync::OnceLock;

/// `NSNotFound`.
pub const NS_NOT_FOUND: i64 = i64::MAX;

// ---------------------------------------------------------------------------------------------------
// UTF-16 helpers

fn utf16(s: &str) -> Vec<u16> {
    s.encode_utf16().collect()
}

fn from_utf16(u: &[u16]) -> String {
    String::from_utf16_lossy(u)
}

/// UTF-16 length.
pub fn length(s: &str) -> usize {
    if s.is_ascii() {
        s.len()
    } else {
        s.encode_utf16().count()
    }
}

/// `-[NSString hash]`: `h = h*33 + c` over UTF-16 units, masked to 28 bits, 0 -> 0x0fffffff, empty -> 0x0ffffffe.
pub fn gs_hash(s: &str) -> u32 {
    if s.is_empty() {
        return 0x0fff_fffe;
    }
    let mut h: u32 = 0;
    for c in s.encode_utf16() {
        h = h.wrapping_mul(33).wrapping_add(c as u32);
    }
    h &= 0x0fff_ffff;
    if h == 0 {
        h = 0x0fff_ffff;
    }
    h
}

