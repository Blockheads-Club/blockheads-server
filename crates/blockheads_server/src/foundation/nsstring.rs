/// `-getSubStringBetween:andEnd:`.
pub fn get_sub_string_between(s: Option<&str>, start: &str, end: &str) -> Option<String> {
    let s = s?;
    let (sl, sn) = range_of_string(s, start)?;
    let from = sl + sn;
    let total = length(s);
    let (el, _) = range_of_string_in(s, end, from, total - from)?;
    Some(substring_with_range(s, from, el - from))
}

/// `-stringByRemovingNonAsciiChars`: keeps only U+0020..=U+007E.
pub fn string_by_removing_non_ascii_chars(s: &str) -> String {
    s.chars().filter(|c| ('\u{20}'..='\u{7e}').contains(c)).collect()
}

/// `strtoul(buf, NULL, 16)` for a buffer of at most two chars (C semantics).
fn strtoul16_two(buf: [u8; 2]) -> u64 {
    let mut i = 0;
    while i < 2 && matches!(buf[i], b' ' | b'\t' | b'\n' | 0x0b | 0x0c | b'\r') {
        i += 1;
    }
    let mut neg = false;
    if i < 2 && (buf[i] == b'+' || buf[i] == b'-') {
        neg = buf[i] == b'-';
        i += 1;
    }
    // "0x" prefix without following hex digit parses as "0" (value 0)
    let mut v: u64 = 0;
    while i < 2 {
        match (buf[i] as char).to_digit(16) {
            Some(d) => {
                v = v * 16 + d as u64;
                i += 1;
            }
            None => break,
        }
    }
    if neg {
        v.wrapping_neg()
    } else {
        v
    }
}

/// `-dataFromHexString`.
pub fn data_from_hex_string(s: &str) -> Vec<u8> {
    let chars = s.as_bytes(); // [self UTF8String]
    let len = length(s);
    let mut out = Vec::with_capacity(len / 2);
    let mut i = 0;
    while i < len {
        let b0 = chars.get(i).copied().unwrap_or(0);
        let b1 = chars.get(i + 1).copied().unwrap_or(0);
        i += 2;
        out.push(strtoul16_two([b0, b1]) as u8);
    }
    out
}

