// Case mapping (5.2)

struct CaseTables {
    upper: Vec<u16>,
    lower: Vec<u16>,
}

fn case_tables() -> &'static CaseTables {
    static T: OnceLock<CaseTables> = OnceLock::new();
    T.get_or_init(|| {
        let mut upper: Vec<u16> = (0..=0xFFFFu32).map(|x| x as u16).collect();
        let mut lower = upper.clone();
        for &(c, u, l) in CASE_TABLE {
            if u != 0 {
                upper[c as usize] = u;
            }
            if l != 0 {
                lower[c as usize] = l;
            }
        }
        CaseTables { upper, lower }
    })
}

fn map_case(s: &str, upper: bool) -> String {
    if s.encode_utf16().all(|u| u <= 0xFF) {
        // 8-bit GSCString path: C-locale toupper/tolower, ASCII only.
        return if upper { s.to_ascii_uppercase() } else { s.to_ascii_lowercase() };
    }
    let t = case_tables();
    let tab = if upper { &t.upper } else { &t.lower };
    let u: Vec<u16> = s.encode_utf16().map(|c| tab[c as usize]).collect();
    from_utf16(&u)
}

/// `-lowercaseString`.
pub fn lowercase_string(s: &str) -> String {
    map_case(s, false)
}

/// `-uppercaseString`.
pub fn uppercase_string(s: &str) -> String {
    map_case(s, true)
}

/// `-capitalizedString`: a unit is word-initial iff first or the previous unit is one of SP TAB LF FF CR
/// (observed). Word-initial units use the uppercase table, others the lowercase table,
/// in all regimes (the 8-bit ASCII-only regime does not apply here).
pub fn capitalized_string(s: &str) -> String {
    let t = case_tables();
    let mut prev_ws = true;
    let mut out = Vec::new();
    for c in s.encode_utf16() {
        out.push(if prev_ws { t.upper[c as usize] } else { t.lower[c as usize] });
        prev_ws = matches!(c, 0x20 | 0x09 | 0x0A | 0x0C | 0x0D);
    }
    from_utf16(&out)
}

