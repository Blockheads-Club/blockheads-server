// Number parsing (5.4, 5.5)

fn is_c_space(c: u16) -> bool {
    matches!(c, 0x20 | 0x09 | 0x0a | 0x0b | 0x0c | 0x0d)
}

/// strtol-like parse with i64 saturation.
fn parse_i64_saturating(s: &str) -> i64 {
    let u = utf16(s);
    let mut i = 0;
    while i < u.len() && is_c_space(u[i]) {
        i += 1;
    }
    let mut neg = false;
    if i < u.len() && (u[i] == b'+' as u16 || u[i] == b'-' as u16) {
        neg = u[i] == b'-' as u16;
        if i + 1 < u.len() && (b'0' as u16..=b'9' as u16).contains(&u[i + 1]) {
            i += 1;
        } else {
            return 0;
        }
    }
    let mut v: i128 = 0;
    while i < u.len() && (b'0' as u16..=b'9' as u16).contains(&u[i]) {
        v = (v * 10 + (u[i] - b'0' as u16) as i128).min(1i128 << 70);
        i += 1;
    }
    let v = if neg { -v } else { v };
    v.clamp(i64::MIN as i128, i64::MAX as i128) as i64
}

/// `-intValue`: saturating i64 parse truncated to the low 32 bits.
pub fn int_value(s: &str) -> i32 {
    parse_i64_saturating(s) as i32
}

/// `-integerValue` (64-bit `long`), saturating.
pub fn integer_value(s: &str) -> i64 {
    parse_i64_saturating(s)
}

/// `-longLongValue`, saturating.
pub fn long_long_value(s: &str) -> i64 {
    parse_i64_saturating(s)
}

/// `-boolValue`: first non-space char (after an optional sign) in `YyTt1-9`; leading zeros skipped.
pub fn bool_value(s: &str) -> bool {
    let u = utf16(s);
    let mut i = 0;
    while i < u.len() && is_c_space(u[i]) {
        i += 1;
    }
    if i < u.len() && (u[i] == b'+' as u16 || u[i] == b'-' as u16) {
        i += 1;
        while i < u.len() && is_c_space(u[i]) {
            i += 1;
        }
    }
    while i < u.len() && u[i] == b'0' as u16 {
        i += 1;
        if i >= u.len() || !(b'0' as u16..=b'9' as u16).contains(&u[i]) {
            return false;
        }
    }
    if i >= u.len() {
        return false;
    }
    matches!(u[i], 0x59 | 0x79 | 0x54 | 0x74 | 0x31..=0x39)
}

/// Correctly rounded `10^e` (what glibc 2.19's `pow` returns).
fn pow10(e: i64) -> f64 {
    let e = e.clamp(-100_000, 100_000);
    format!("1e{}", e).parse::<f64>().unwrap_or(f64::NAN)
}

/// `-doubleValue`: custom parser (`v = v*10 + digit` over all mantissa digits, then `v * 10^(exp - fracdigits)`).
pub fn double_value(s: &str) -> f64 {
    let u = utf16(s);
    let n = u.len();
    let mut i = 0;
    while i < n && is_c_space(u[i]) {
        i += 1;
    }
    let mut neg = false;
    if i < n && (u[i] == b'+' as u16 || u[i] == b'-' as u16) {
        neg = u[i] == b'-' as u16;
        i += 1;
    }
    let digit = |c: u16| -> Option<u32> {
        if (0x30..=0x39).contains(&c) {
            Some((c - 0x30) as u32)
        } else {
            None
        }
    };
    let mut v = 0.0f64;
    let mut ndigits = 0usize;
    while i < n {
        match digit(u[i]) {
            Some(d) => {
                v = v * 10.0 + d as f64;
                ndigits += 1;
                i += 1;
            }
            None => break,
        }
    }
    let mut frac = 0i64;
    if i < n && u[i] == b'.' as u16 {
        i += 1;
        while i < n {
            match digit(u[i]) {
                Some(d) => {
                    v = v * 10.0 + d as f64;
                    ndigits += 1;
                    frac += 1;
                    i += 1;
                }
                None => break,
            }
        }
    }
    if ndigits == 0 {
        return 0.0;
    }
    let mut exp: i64 = 0;
    if i < n && (u[i] == b'e' as u16 || u[i] == b'E' as u16) {
        i += 1;
        let mut eneg = false;
        if i < n && (u[i] == b'+' as u16 || u[i] == b'-' as u16) {
            eneg = u[i] == b'-' as u16;
            i += 1;
        }
        let mut edigits = 0;
        let mut ev: i64 = 0;
        while i < n {
            match digit(u[i]) {
                Some(d) => {
                    ev = (ev * 10 + d as i64).min(1_000_000);
                    edigits += 1;
                    i += 1;
                }
                None => break,
            }
        }
        if edigits == 0 {
            return 0.0; // dangling exponent
        }
        exp = if eneg { -ev } else { ev };
    }
    let e10 = exp - frac;
    // LIBM-PARITY: correctly rounded power of ten instead of host `pow`.
    let r = v * pow10(e10);
    if neg {
        -r
    } else {
        r
    }
}

/// `-floatValue` = `(float)doubleValue`.
pub fn float_value(s: &str) -> f32 {
    double_value(s) as f32
}

