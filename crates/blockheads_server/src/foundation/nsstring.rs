// Prefix / suffix / ranges (5.6)

/// Decomposed haystack with a map back to original UTF-16 offsets.
struct Decomp {
    units: Vec<u16>,
    /// original UTF-16 offset of the char each unit belongs to
    off: Vec<usize>,
    /// true when the unit is the first unit of its original char
    start: Vec<bool>,
    total: usize,
}

fn decomp_with_map(s: &str) -> Decomp {
    let mut d = Decomp { units: vec![], off: vec![], start: vec![], total: 0 };
    let mut pos = 0usize;
    for ch in s.chars() {
        let mut cps = Vec::new();
        push_decomposed(ch, &mut cps, false);
        let us = cps_to_units(&cps);
        for (k, u) in us.iter().enumerate() {
            d.units.push(*u);
            d.off.push(pos);
            d.start.push(k == 0);
        }
        pos += ch.len_utf16();
    }
    d.total = pos;
    d
}

impl Decomp {
    fn boundary(&self, j: usize) -> bool {
        j == self.units.len() || self.start[j]
    }
    fn orig(&self, j: usize) -> usize {
        if j == self.units.len() {
            self.total
        } else {
            self.off[j]
        }
    }
}

fn find_decomp(h: &Decomp, needle: &[u16], anchored_start: bool, anchored_end: bool) -> Option<(usize, usize)> {
    let m = needle.len();
    if m == 0 || m > h.units.len() {
        return None;
    }
    let range: Vec<usize> = if anchored_start {
        vec![0]
    } else if anchored_end {
        vec![h.units.len() - m]
    } else {
        (0..=h.units.len() - m).collect()
    };
    for i in range {
        if h.units[i..i + m] == *needle && h.boundary(i) && h.boundary(i + m) {
            let a = h.orig(i);
            let b = h.orig(i + m);
            return Some((a, b - a));
        }
    }
    None
}

/// `-hasPrefix:` (empty prefix: not found, inferred).
pub fn has_prefix(s: &str, p: &str) -> bool {
    if p.is_empty() {
        return false;
    }
    if s.is_ascii() && p.is_ascii() {
        return s.starts_with(p);
    }
    find_decomp(&decomp_with_map(s), &nfd_units(p), true, false).is_some()
}

/// `-hasSuffix:` (empty suffix: not found, inferred).
pub fn has_suffix(s: &str, p: &str) -> bool {
    if p.is_empty() {
        return false;
    }
    if s.is_ascii() && p.is_ascii() {
        return s.ends_with(p);
    }
    find_decomp(&decomp_with_map(s), &nfd_units(p), false, true).is_some()
}

/// `-rangeOfString:` first occurrence, non-literal (canonical equivalence) as UTF-16 `(location, length)`;
/// empty needle -> None.
pub fn range_of_string(s: &str, needle: &str) -> Option<(usize, usize)> {
    if needle.is_empty() {
        return None;
    }
    if s.is_ascii() && needle.is_ascii() {
        return s.find(needle).map(|i| (i, needle.len()));
    }
    find_decomp(&decomp_with_map(s), &nfd_units(needle), false, false)
}

/// `-rangeOfString:options:range:` with options 0. Raises `NSRangeException` on a bad range.
pub fn range_of_string_in(s: &str, needle: &str, loc: usize, len: usize) -> Option<(usize, usize)> {
    let size = length(s);
    if loc as u64 + len as u64 > size as u64 {
        range_exception_beyond_size("rangeOfString:options:range:", loc as u64, len as u64, size as u64);
    }
    let sub = substring_with_range(s, loc, len);
    range_of_string(&sub, needle).map(|(l, n)| (l + loc, n))
}

/// `-substringWithRange:`; raises `NSRangeException` when `loc+len > size`.
pub fn substring_with_range(s: &str, loc: usize, len: usize) -> String {
    let size = length(s);
    if loc as u64 + len as u64 > size as u64 {
        range_exception_beyond_size("substringWithRange:", loc as u64, len as u64, size as u64);
    }
    if s.is_ascii() {
        return s[loc..loc + len].to_string();
    }
    let u = utf16(s);
    from_utf16(&u[loc..loc + len])
}

/// `-substringToIndex:`; `i > size` raises with range `{ 0, i }`.
pub fn substring_to_index(s: &str, i: usize) -> String {
    substring_with_range(s, 0, i)
}

/// `-substringFromIndex:`; `i > size` raises with range `{ i, (S - i) in u32 }`.
pub fn substring_from_index(s: &str, i: usize) -> String {
    let size = length(s);
    if i > size {
        let l = (size as u32).wrapping_sub(i as u32) as u64;
        range_exception_beyond_size("substringWithRange:", i as u64, l, size as u64);
    }
    substring_with_range(s, i, size - i)
}

/// `-characterAtIndex:`; raises `NSRangeException` "Invalid index.".
pub fn character_at_index(s: &str, i: usize) -> u16 {
    if i >= length(s) {
        ns_raise("NSRangeException", "Invalid index.");
    }
    s.encode_utf16().nth(i).unwrap()
}

/// `-componentsSeparatedByString:`: repeated `rangeOfString:options:0 range:` (non-literal search, 5.6) over the
/// remaining range; an empty separator is never found, giving `[s]`.
// Note: GNUstep behaviour for an empty separator (not-found => [self] assumed).
pub fn components_separated_by_string(s: &str, sep: &str) -> Vec<String> {
    if sep.is_empty() {
        return vec![s.to_string()];
    }
    if s.is_ascii() && sep.is_ascii() {
        return s.split(sep).map(|x| x.to_string()).collect();
    }
    let total = length(s);
    let mut out = Vec::new();
    let mut loc = 0usize;
    while let Some((fl, fn_)) = range_of_string_in(s, sep, loc, total - loc) {
        out.push(substring_with_range(s, loc, fl - loc));
        loc = fl + fn_;
    }
    out.push(substring_with_range(s, loc, total - loc));
    out
}

