// Canonical decomposition (NFD) for compare / range search

struct NfdTables {
    decomp: HashMap<u32, (usize, usize, bool)>,
    ccc: HashMap<u32, u8>,
}

fn nfd_tables() -> &'static NfdTables {
    static T: OnceLock<NfdTables> = OnceLock::new();
    T.get_or_init(|| {
        let mut decomp = HashMap::new();
        let mut i = 0;
        while i < NFD_FLAT.len() {
            let cp = NFD_FLAT[i];
            let n = NFD_FLAT[i + 1] as usize;
            decomp.insert(cp, (i + 3, n, NFD_FLAT[i + 2] != 0));
            i += 3 + n;
        }
        let mut ccc = HashMap::new();
        let mut j = 0;
        while j < CCC_FLAT.len() {
            ccc.insert(CCC_FLAT[j], CCC_FLAT[j + 1] as u8);
            j += 2;
        }
        NfdTables { decomp, ccc }
    })
}

/// Sort-key sentinel appended to non-"clean" table expansions (inferred model).
const NFD_SENTINEL: u32 = 0x02FF;

/// GNUstep single-level decomposition (no Hangul, no recursion). With `sentinel`, entries whose observed
/// `compare(x, expansion) != 0` get a trailing sentinel so they sort just above their expansion.
fn push_decomposed(ch: char, out: &mut Vec<u32>, sentinel: bool) {
    let cp = ch as u32;
    if cp < 0x80 {
        out.push(cp);
    } else if let Some(&(off, n, clean)) = nfd_tables().decomp.get(&cp) {
        out.extend_from_slice(&NFD_FLAT[off..off + n]);
        if sentinel && !clean {
            out.push(NFD_SENTINEL);
        }
    } else {
        out.push(cp);
    }
}

fn reorder(cps: &mut [u32]) {
    let t = nfd_tables();
    let mut i = 0;
    while i < cps.len() {
        if t.ccc.get(&cps[i]).copied().unwrap_or(0) == 0 {
            i += 1;
            continue;
        }
        let mut j = i;
        while j < cps.len() && t.ccc.get(&cps[j]).copied().unwrap_or(0) != 0 {
            j += 1;
        }
        cps[i..j].sort_by_key(|c| t.ccc.get(c).copied().unwrap_or(0));
        i = j;
    }
}

fn cps_to_units(cps: &[u32]) -> Vec<u16> {
    let mut out = Vec::with_capacity(cps.len());
    for &c in cps {
        let ch = char::from_u32(c).unwrap_or('\u{FFFD}');
        let mut b = [0u16; 2];
        out.extend_from_slice(ch.encode_utf16(&mut b));
    }
    out
}

/// NFD of a string as UTF-16 units.
fn nfd_units(s: &str) -> Vec<u16> {
    nfd_units_opt(s, false)
}

/// Sort key (UTF-16 units) with GNUstep table decomposition.
fn nfd_units_opt(s: &str, _protect: bool) -> Vec<u16> {
    if s.is_ascii() {
        return utf16(s);
    }
    let mut cps = Vec::new();
    for ch in s.chars() {
        push_decomposed(ch, &mut cps, true);
    }
    reorder(&mut cps);
    cps_to_units(&cps)
}

fn cmp3(a: &[u16], b: &[u16]) -> i32 {
    match a.cmp(b) {
        std::cmp::Ordering::Less => -1,
        std::cmp::Ordering::Equal => 0,
        std::cmp::Ordering::Greater => 1,
    }
}

/// `-compare:`: lexicographic compare of NFD forms as UTF-16 units, -1/0/1.
pub fn compare(a: &str, b: &str) -> i32 {
    cmp3(&nfd_units(a), &nfd_units(b))
}

/// `-caseInsensitiveCompare:`: table decomposition first, then fold every unit with the lowercase table.
/// observed: U+0130 behaves as `I U+0307` then folded, U+212A as `k`+sentinel.
pub fn case_insensitive_compare(a: &str, b: &str) -> i32 {
    if a.is_ascii() && b.is_ascii() {
        let x = a.bytes().map(|c| c.to_ascii_lowercase());
        let y = b.bytes().map(|c| c.to_ascii_lowercase());
        return match x.cmp(y) {
            std::cmp::Ordering::Less => -1,
            std::cmp::Ordering::Equal => 0,
            std::cmp::Ordering::Greater => 1,
        };
    }
    let t = case_tables();
    let fold = |s: &str| -> Vec<u16> { nfd_units_opt(s, false).into_iter().map(|c| t.lower[c as usize]).collect() };
    cmp3(&fold(a), &fold(b))
}

/// `-safeCaseInsensitiveCompare:`: nil receiver -> 0, nil other -> NSOrderedDescending (1).
pub fn safe_case_insensitive_compare(recv: Option<&str>, other: Option<&str>) -> i32 {
    match (recv, other) {
        (None, _) => 0,
        (Some(_), None) => 1,
        (Some(a), Some(b)) => case_insensitive_compare(a, b),
    }
}

/// `-isEqualToString:`: exact UTF-16 equality.
pub fn is_equal(a: &str, b: &str) -> bool {
    a == b
}

