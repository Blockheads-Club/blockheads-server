//! fmath::libm parity against glibc 2.19 vectors produced by `libm_probe` inside the reference image.
//!
//! Vector file record: `u8 fn_id; u8 nargs; args (u32 bits for f32 functions, u64 for f64); result bits`.
//! fn_id: 0 sin 1 cos 2 pow 3 atan2 4 floor 5 fmod 6 sqrt 7 sinf 8 cosf 9 tanf 10 powf 11 atan2f 12 fmodf 13 sqrtf.

use blockheads_server::fmath::libm;

const NAMES: [&str; 14] =
    ["sin", "cos", "pow", "atan2", "floor", "fmod", "sqrt", "sinf", "cosf", "tanf", "powf", "atan2f", "fmodf", "sqrtf"];

struct Rec {
    id: usize,
    a: u64,
    b: u64,
    r: u64,
}

fn parse(data: &[u8]) -> Vec<Rec> {
    let mut v = Vec::new();
    let mut i = 0;
    while i < data.len() {
        let id = data[i] as usize;
        let n = data[i + 1] as usize;
        i += 2;
        let w = if id <= 6 { 8 } else { 4 };
        let rd = |off: usize| -> u64 {
            let mut x = 0u64;
            for k in 0..w {
                x |= (data[off + k] as u64) << (8 * k);
            }
            x
        };
        let a = rd(i);
        i += w;
        let b = if n == 2 {
            let b = rd(i);
            i += w;
            b
        } else {
            0
        };
        let r = rd(i);
        i += w;
        v.push(Rec { id, a, b, r });
    }
    v
}

fn eval(rec: &Rec) -> u64 {
    let x = f64::from_bits(rec.a);
    let y = f64::from_bits(rec.b);
    let xf = f32::from_bits(rec.a as u32);
    let yf = f32::from_bits(rec.b as u32);
    match rec.id {
        0 => libm::sin(x).to_bits(),
        1 => libm::cos(x).to_bits(),
        2 => libm::pow(x, y).to_bits(),
        3 => libm::atan2(x, y).to_bits(),
        4 => libm::floor(x).to_bits(),
        5 => libm::fmod(x, y).to_bits(),
        6 => libm::sqrt(x).to_bits(),
        7 => libm::sinf(xf).to_bits() as u64,
        8 => libm::cosf(xf).to_bits() as u64,
        9 => libm::tanf(xf).to_bits() as u64,
        10 => libm::powf(xf, yf).to_bits() as u64,
        11 => libm::atan2f(xf, yf).to_bits() as u64,
        12 => libm::fmodf(xf, yf).to_bits() as u64,
        13 => libm::sqrtf(xf).to_bits() as u64,
        _ => panic!("bad fn id"),
    }
}

fn check(recs: &[Rec], only: Option<usize>) -> (usize, usize) {
    let mut bad = 0;
    let mut total = 0;
    let mut shown = 0;
    let mut per_fn = [0usize; 14];
    for r in recs {
        if let Some(o) = only {
            if r.id != o {
                continue;
            }
        }
        total += 1;
        let got = eval(r);
        if got != r.r {
            bad += 1;
            per_fn[r.id] += 1;
            if shown < 20 {
                shown += 1;
                eprintln!("MISMATCH {} a={:#x} b={:#x} expected={:#x} got={:#x}", NAMES[r.id], r.a, r.b, r.r, got);
            }
        }
    }
    for (i, c) in per_fn.iter().enumerate() {
        if *c > 0 {
            eprintln!("  {}: {} mismatches", NAMES[i], c);
        }
    }
    (bad, total)
}

fn sweep() -> Vec<Rec> {
    parse(include_bytes!("data/libm_vectors.bin"))
}

macro_rules! per_fn_test {
    ($name:ident, $id:expr) => {
        #[test]
        fn $name() {
            let (bad, total) = check(&sweep(), Some($id));
            assert!(total > 1000, "vectors missing");
            assert_eq!(bad, 0, "{} mismatches out of {}", bad, total);
        }
    };
}

per_fn_test!(sweep_sin, 0);
per_fn_test!(sweep_cos, 1);
per_fn_test!(sweep_pow, 2);
per_fn_test!(sweep_atan2, 3);
per_fn_test!(sweep_floor, 4);
per_fn_test!(sweep_fmod, 5);
per_fn_test!(sweep_sqrt, 6);
per_fn_test!(sweep_sinf, 7);
per_fn_test!(sweep_cosf, 8);
per_fn_test!(sweep_tanf, 9);
per_fn_test!(sweep_powf, 10);
per_fn_test!(sweep_atan2f, 11);
per_fn_test!(sweep_fmodf, 12);
per_fn_test!(sweep_sqrtf, 13);

/// Optional extra vector files (e.g. a larger `libm_probe sweep <seed> <N>` run or gdb captured
/// arguments evaluated by `libm_probe eval`): `LIBM_EXTRA_VECTORS=a.bin:b.bin cargo test`.
#[test]
fn extra_vectors_from_env() {
    let Ok(list) = std::env::var("LIBM_EXTRA_VECTORS") else { return };
    for path in list.split(':').filter(|s| !s.is_empty()) {
        let data = std::fs::read(path).expect("read extra vectors");
        let recs = parse(&data);
        let (bad, total) = check(&recs, None);
        assert_eq!(bad, 0, "{path}: {bad} mismatches out of {total}");
    }
}

/// Checklist item 3: independent mpmath oracle (400 bit, rounded to nearest) for the four
/// correctly rounded f64 functions; glibc 2.19 has 0 mismatches against it, so any mismatch here is a
/// Rust bug. Generated by `tools/libm_probe/`.
#[test]
fn oracle_correct_rounding() {
    let recs = parse(include_bytes!("data/libm_oracle.bin"));
    assert!(recs.len() > 70000);
    let (bad, total) = check(&recs, None);
    assert_eq!(bad, 0, "{bad} mismatches out of {total}");
}

struct Xs(u64);
impl Xs {
    fn next(&mut self) -> u64 {
        let mut x = self.0;
        x ^= x << 13;
        x ^= x >> 7;
        x ^= x << 17;
        self.0 = x;
        x
    }
    fn unit(&mut self) -> f64 {
        (self.next() >> 11) as f64 / 9007199254740992.0
    }
}

/// The double-double fast path of sin/cos must agree with the exact slow path.
#[test]
fn sincos_fast_path_equals_exact_path() {
    let mut r = Xs(0x1234_5678_9abc_def1);
    for i in 0..6000 {
        let x = match i % 4 {
            0 => (r.unit() - 0.5) * 80.0,
            1 => (r.unit() - 0.5) * 3.2e6,
            2 => (r.unit() - 0.5) * 2.0,
            _ => f64::from_bits(r.next() & 0x7fef_ffff_ffff_ffff) * if i % 8 < 4 { 1.0 } else { -1.0 },
        };
        if !x.is_finite() {
            continue;
        }
        assert_eq!(libm::sin(x).to_bits(), libm::sin_exact(x).to_bits(), "sin({x:e})");
        assert_eq!(libm::cos(x).to_bits(), libm::cos_exact(x).to_bits(), "cos({x:e})");
    }
}

/// pow/atan2 results must not depend on the precision level reached.
#[test]
fn pow_atan2_public_equals_exact() {
    let mut r = Xs(0x0f0f_1234_5678_9abd);
    for _ in 0..1500 {
        let x = r.unit() * 10.0 + 1e-3;
        let y = (r.unit() - 0.5) * 100.0;
        assert_eq!(libm::pow(x, y).to_bits(), libm::pow_exact(x, y).to_bits());
        let a = (r.unit() - 0.5) * 10.0;
        let b = (r.unit() - 0.5) * 10.0;
        assert_eq!(libm::atan2(a, b).to_bits(), libm::atan2_exact(a, b).to_bits());
    }
}

/// The special-case result constants (pi, pi/2, pi/4, 3pi/4) are the correctly rounded values.
#[test]
fn atan2_constants_are_correctly_rounded() {
    let c = libm::pi_rounded_multiples();
    assert_eq!(c[0], libm::atan2(0.0, -1.0));
    assert_eq!(c[1], libm::atan2(1.0, 0.0));
    assert_eq!(c[2], libm::atan2(f64::INFINITY, f64::INFINITY));
    assert_eq!(c[3], libm::atan2(f64::INFINITY, f64::NEG_INFINITY));
    assert_eq!(c[0], std::f64::consts::PI);
}

/// Checklist item 4: special value table (values verified against the glibc 2.19 sweep above).
#[test]
fn special_values() {
    use libm::*;
    assert_eq!(sin(0.0).to_bits(), 0.0f64.to_bits());
    assert_eq!(sin(-0.0).to_bits(), (-0.0f64).to_bits());
    assert!(sin(f64::INFINITY).is_nan() && cos(f64::NEG_INFINITY).is_nan());
    assert_eq!(cos(0.0), 1.0);
    assert_eq!(cos(1e22).to_bits(), (0.523214785395139f64).to_bits());
    assert_eq!(sin(1e22).to_bits(), (-0.8522008497671888f64).to_bits());
    assert_eq!(pow(3.5, 0.0), 1.0);
    assert_eq!(pow(f64::NAN, 0.0), 1.0);
    assert_eq!(pow(1.0, f64::NAN), 1.0);
    assert!(pow(-8.0, 1.0 / 3.0).is_nan());
    assert_eq!(pow(0.0, -1.0), f64::INFINITY);
    assert_eq!(pow(-0.0, -1.0), f64::NEG_INFINITY);
    assert_eq!(pow(-2.0, 3.0), -8.0);
    assert_eq!(pow(2.0, -1074.0), 5e-324);
    assert_eq!(pow(2.0, -1075.0), 0.0);
    assert_eq!(pow(2.0, 1024.0), f64::INFINITY);
    assert_eq!(pow(0.999, 1e9), 0.0);
    assert_eq!(pow(0.999, -1e9), f64::INFINITY);
    assert_eq!(atan2(0.0, -0.0).to_bits(), std::f64::consts::PI.to_bits());
    assert_eq!(atan2(-0.0, -0.0).to_bits(), (-std::f64::consts::PI).to_bits());
    assert_eq!(atan2(0.0, 0.0).to_bits(), 0);
    assert_eq!(atan2(-0.0, 1.0).to_bits(), (-0.0f64).to_bits());
    assert_eq!(atan2(1.0, 1.0), std::f64::consts::FRAC_PI_4);
    assert!(fmod(1.0, 0.0).is_nan());
    assert_eq!(fmod(-5.5, 2.0), -1.5);
    assert!(fmodf(f32::INFINITY, 2.0).is_nan());
    assert_eq!(fmodf(-0.75, 0.5), -0.25);
    // f32
    assert_eq!(powf(0.0, 0.0), 1.0);
    assert_eq!(sinf(0.0).to_bits(), 0);
    assert_eq!(sinf(-0.0).to_bits(), 0x8000_0000);
    assert!(sinf(f32::INFINITY).is_nan() && cosf(f32::INFINITY).is_nan() && tanf(f32::INFINITY).is_nan());
    assert_eq!(cosf(0.0), 1.0);
    assert_eq!(atan2f(1.0, 1.0), std::f32::consts::FRAC_PI_4);
    assert_eq!(sqrt(2.25), 1.5);
    assert_eq!(sqrtf(2.25), 1.5);
    assert_eq!(floor(-1.5), -2.0);
    assert_eq!(fabsf(f32::from_bits(0xffc0_0001)).to_bits(), 0x7fc0_0001);
    assert_eq!(fabs(-0.0).to_bits(), 0);
}
